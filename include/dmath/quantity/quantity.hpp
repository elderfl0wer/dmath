#ifndef QUANTITY_HPP
#define QUANTITY_HPP

#include "../concepts/numeric.hpp"

namespace dmath {
struct loose_dimension {};
struct strict_dimension {};

template<numeric T, class Unit, typename DimensionPolicy = loose_dimension>
class quantity
{
private:
    T data;

public:
    using quantity_strict = quantity<T, Unit, strict_dimension>;
    constexpr explicit quantity(T value): data(value) {};

    constexpr quantity_strict operator+(const quantity_strict& other) const {
        return {.data = this->data-other.data};
    }
    constexpr quantity_strict operator-(const quantity_strict& other) const {
        return {.data = this->data-other.data};
    }
    // operator!= is auto-generated by C++20 by overload of operator==
    constexpr bool operator==(const quantity_strict& other) const {
        return (this->data == other.data) ? true : false;
    }
    constexpr auto operator<=>(const quantity_strict& other) const = default;
    constexpr quantity_strict operator+() const;
    constexpr quantity_strict operator-() const;
    constexpr quantity_strict operator*(const T factor) { return this->data*factor; }
    constexpr quantity_strict operator/(const T factor) { return this->data/factor; }
    constexpr quantity<T, class returnUnit> operator*(const quantity<T, class parameterUnit>& other) const {
        quantity<T, returnUnit> qt(this->data*other.data);
        return qt;
    }
    constexpr quantity<T, class returnUnit> operator/(const quantity<T, class parameterUnit>& other) const {
        quantity<T, returnUnit> qt(this->data/other.data);
        return qt;
    }

    using quantity_loose = quantity<T, Unit, loose_dimension>;
    constexpr quantity_strict operator+(const quantity_strict& other) const {
        quantity_strict qts = qts(this->data+other.data);
        return qts;
    }
};
} // !NAMESPACE DMATH

#endif // QUANTITY_HPP
